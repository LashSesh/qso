/// The orbits of the permutation group generated by `generators`
/// (permutations `u ↦ g[u]` of `0..n`) on ordered pairs of points: the
/// entries an invariant operator has in common. Up to 8192 points by
/// union–find over all pairs; beyond, from the orbits of the stabilisers of
/// points (memory linear in the points), where the dense `coefficients` and
/// `operator` are not available.
#[pyclass(name = "Orbitals", module = "metatron_qso", frozen)]
pub struct PyOrbitals {
    inner: Arc<Orbitals>,
}

#[pymethods]
impl PyOrbitals {
    #[new]
    #[pyo3(signature = (n, generators = Vec::new()))]
    fn new(py: Python<'_>, n: usize, generators: Vec<Vec<usize>>) -> PyResult<Self> {
        py.detach(|| Orbitals::new(n, &generators))
            .raise()
            .map(|o| Self { inner: Arc::new(o) })
    }

    #[getter]
    fn num_points(&self) -> usize {
        self.inner.num_points()
    }

    fn __len__(&self) -> usize {
        self.inner.len()
    }

    /// The orbital of the pair `(u, v)`.
    fn of(&self, u: usize, v: usize) -> PyResult<usize> {
        let n = self.inner.num_points();
        if u >= n || v >= n {
            return Err(invalid(format!(
                "pair ({u}, {v}) out of range for {n} points"
            )));
        }
        Ok(self.inner.of(u, v))
    }

    /// The first pair of orbital `o`.
    fn representative(&self, o: usize) -> PyResult<(usize, usize)> {
        self.check(o)?;
        Ok(self.inner.representative(o))
    }

    /// Number of pairs in orbital `o`.
    fn size(&self, o: usize) -> PyResult<usize> {
        self.check(o)?;
        Ok(self.inner.size(o))
    }

    /// The coefficients of an `n × n` operator constant on every orbital
    /// (to `tol` of its largest entry; up to 8192 points).
    #[pyo3(signature = (m, tol = 1e-10))]
    fn coefficients<'py>(
        &self,
        py: Python<'py>,
        m: ComplexMatrixArg<'_>,
        tol: f64,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (dim, data) = square_complex("m", &m)?;
        let m = CMatrix::from_row_slice(dim, dim, &data);
        Ok(complex_array(py, self.inner.coefficients(&m, tol).raise()?))
    }

    /// The `n × n` operator with coefficients `x` (up to 8192 points).
    fn operator<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray2<C64>>> {
        Ok(cmatrix(py, &self.inner.operator(&complex_vec(&x)).raise()?))
    }

    fn __repr__(&self) -> String {
        format!(
            "Orbitals(points={}, orbitals={})",
            self.inner.num_points(),
            self.inner.len()
        )
    }
}

impl PyOrbitals {
    fn check(&self, o: usize) -> PyResult<()> {
        if o >= self.inner.len() {
            return Err(invalid(format!(
                "orbital {o} out of range for {} orbitals",
                self.inner.len()
            )));
        }
        Ok(())
    }
}

/// `(rate, block)` pairs: dephasing at `rate` between the blocks of the
/// partition `block` (node → block label).
fn dephasing(terms: Vec<(f64, Vec<usize>)>) -> Vec<Dephasing> {
    terms
        .into_iter()
        .map(|(rate, block)| Dephasing { rate, block })
        .collect()
}

/// A continuous-time walk `H = γL` or `−γA` with dephasing
/// `dρ/dt = −i[H, ρ] + Σ_m κ_m (Σ_j P_{m,j} ρ P_{m,j} − ρ)`, reduced to the
/// orbitals of the group generated by `symmetries`.
///
/// `dephasing` is a list of `(rate, block)` pairs, `block[u]` the block of
/// node `u` in that term's partition: `(κ, list(range(n)))` is site
/// dephasing, `(κ, [(u >> k) & 1 for u in range(n)])` dephasing of
/// coordinate `k` of a hypercube. The symmetries must be automorphisms of
/// the graph under which the total decay rate of every entry is invariant;
/// `graph.stabilizer_generators` and `coordinate_permutations` give some
/// (prefer small generating sets: the work grows with their number).
/// Beyond 8192 nodes the orbitals come from the stabilisers of points, and
/// the dephasing must be kept term by term: every symmetry maps each
/// partition (terms with the same partition merged) onto one of the same
/// rate.
///
/// For transport to a trap, `site_energies`, `node_dephasing` (added to
/// the `dephasing` terms), `traps` (`{node: κ}` or `(node, κ)` pairs) and
/// `losses` (a number or one per node) must each be equal on every orbit
/// of nodes under the symmetries; a whole orbit of traps of equal rate is
/// allowed.
#[pyclass(name = "SymmetricOpenWalk", module = "metatron_qso", frozen)]
pub struct PySymmetricOpenWalk {
    inner: SymmetricOpenWalk,
}

#[pymethods]
impl PySymmetricOpenWalk {
    #[new]
    #[pyo3(signature = (
        graph, generator = "laplacian", gamma = 1.0, dephasing = Vec::new(),
        symmetries = Vec::new(), site_energies = None, node_dephasing = None, traps = None,
        losses = None
    ))]
    #[allow(clippy::too_many_arguments)]
    fn new(
        py: Python<'_>,
        graph: &PyGraph,
        generator: &str,
        gamma: f64,
        dephasing: Vec<(f64, Vec<usize>)>,
        symmetries: Vec<Vec<usize>>,
        site_energies: Option<RealArg<'_>>,
        node_dephasing: Option<RealArg<'_>>,
        traps: Option<Bound<'_, PyAny>>,
        losses: Option<Bound<'_, PyAny>>,
    ) -> PyResult<Self> {
        let (gen_, terms, g) = (
            self::generator(generator)?,
            self::dephasing(dephasing),
            &graph.inner,
        );
        let n = g.num_nodes();
        let energies = site_energies.as_ref().map(real_vec);
        let node_rates = node_dephasing.as_ref().map(real_vec);
        let traps = traps.as_ref().map(traps_arg).transpose()?;
        let losses = losses
            .as_ref()
            .map(|l| rates_arg("losses", l, n))
            .transpose()?;
        py.detach(|| -> metatron_qso::Result<SymmetricOpenWalk> {
            let mut w = SymmetricOpenWalk::new(g, gen_, gamma, &terms, &symmetries)?;
            if let Some(e) = &energies {
                w = w.with_site_energies(e)?;
            }
            if let Some(r) = &node_rates {
                w = w.with_node_dephasing(r)?;
            }
            if let Some(t) = &traps {
                w = w.with_traps(t)?;
            }
            if let Some(l) = &losses {
                w = w.with_losses(l)?;
            }
            Ok(w)
        })
        .raise()
        .map(|inner| Self { inner })
    }

    /// Efficiency `η`, mean arrival time `τ`, losses and dark weight of a
    /// walker started at `start` (fixed by every symmetry), by linear
    /// solves on the orbitals; needs a trap.
    #[pyo3(signature = (start, *, dark_tolerance = 1e-10, tolerance = 1e-13, max_iterations = 1000))]
    fn transport<'py>(
        &self,
        py: Python<'py>,
        start: usize,
        dark_tolerance: f64,
        tolerance: f64,
        max_iterations: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let o = transport_options(dark_tolerance, tolerance, max_iterations);
        let w = &self.inner;
        transport_dict(py, py.detach(|| w.transport(start, &o)).raise()?)
    }

    /// `transport` with each of `rates` (`≥ 0`) added to every node's
    /// dephasing: arrays over the rates.
    #[pyo3(signature = (
        start, rates, *, dark_tolerance = 1e-10, tolerance = 1e-13, max_iterations = 1000
    ))]
    fn dephasing_scan<'py>(
        &self,
        py: Python<'py>,
        start: usize,
        rates: RealArg<'_>,
        dark_tolerance: f64,
        tolerance: f64,
        max_iterations: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let rates = real_vec(&rates);
        let o = transport_options(dark_tolerance, tolerance, max_iterations);
        let w = &self.inner;
        let results = py.detach(|| w.dephasing_scan(start, &rates, &o)).raise()?;
        scan_dict(py, rates, results, w.traps().len())
    }

    /// The rate in `[low, high]` which, added to every node's dephasing,
    /// gives the highest efficiency, with the result there.
    #[pyo3(signature = (
        start, low = 1e-3, high = 1e3, *, dark_tolerance = 1e-10, tolerance = 1e-13,
        max_iterations = 1000
    ))]
    #[allow(clippy::too_many_arguments)]
    fn optimal_dephasing<'py>(
        &self,
        py: Python<'py>,
        start: usize,
        low: f64,
        high: f64,
        dark_tolerance: f64,
        tolerance: f64,
        max_iterations: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let o = transport_options(dark_tolerance, tolerance, max_iterations);
        let w = &self.inner;
        let best = py
            .detach(|| w.optimal_dephasing(start, low, high, &o))
            .raise()?;
        optimum_dict(py, best)
    }

    /// Populations (per node), sink populations (per trap) and the lost
    /// population at each of `times` (non-decreasing) from `start`.
    fn transport_trace<'py>(
        &self,
        py: Python<'py>,
        start: usize,
        times: RealArg<'_>,
    ) -> PyResult<Bound<'py, PyDict>> {
        let times = real_vec(&times);
        let w = &self.inner;
        let states = py.detach(|| w.transport_trace(start, &times)).raise()?;
        let n = w.orbitals().num_points();
        trace_dict(py, states, n, w.traps().len())
    }

    /// The traps `(node, κ)` in the order given.
    #[getter]
    fn traps(&self) -> Vec<(usize, f64)> {
        self.inner.traps().to_vec()
    }

    #[getter]
    fn num_orbitals(&self) -> usize {
        self.inner.num_orbitals()
    }

    /// The orbitals the state lives on.
    #[getter]
    fn orbitals(&self) -> PyOrbitals {
        PyOrbitals {
            inner: Arc::clone(self.inner.orbitals()),
        }
    }

    /// The coefficients of the walker at `node` (fixed by every symmetry).
    fn localized<'py>(&self, py: Python<'py>, node: usize) -> PyResult<Bound<'py, PyArray1<C64>>> {
        Ok(complex_array(py, self.inner.localized(node).raise()?))
    }

    /// The coefficients of the uniform superposition of all nodes.
    fn uniform<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.uniform())
    }

    /// The coefficients after time `t ≥ 0` from `x0`.
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        x0: ComplexArg<'_>,
        t: f64,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (x0, w) = (complex_vec(&x0), &self.inner);
        Ok(complex_array(py, py.detach(|| w.evolve(&x0, t)).raise()?))
    }

    /// The population of every node.
    fn populations<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner.populations(&complex_vec(&x)).raise()?,
        ))
    }
}

