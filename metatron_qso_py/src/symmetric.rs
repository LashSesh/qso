/// A walk on the Cartesian product of graphs whose factors dephase
/// independently, from a product state: `factors` is a list of
/// `(DephasingWalk, copies)`; the hypercube `Q_d` with dephasing per
/// coordinate is `[(DephasingWalk(complete(2), …), d)]`.
#[pyclass(name = "ProductOpenWalk", module = "metatron_qso", frozen)]
pub struct PyProductOpenWalk {
    inner: ProductOpenWalk,
}

#[pymethods]
impl PyProductOpenWalk {
    #[new]
    fn new(factors: Vec<(PyRef<'_, PyDephasingWalk>, usize)>) -> PyResult<Self> {
        let factors = factors.iter().map(|(w, k)| (w.inner.clone(), *k)).collect();
        ProductOpenWalk::new(factors)
            .raise()
            .map(|inner| Self { inner })
    }

    /// The node populations of each factor at time `t`, every copy of
    /// factor `k` started at `starts[k]`.
    fn marginals(&self, py: Python<'_>, starts: Vec<usize>, t: f64) -> PyResult<Vec<Vec<f64>>> {
        let w = &self.inner;
        py.detach(|| w.marginals(&starts, t)).raise()
    }

    /// The distribution of the number of copies at their target node
    /// (`targets[k]` for factor `k`), from `marginals`.
    fn count_distribution<'py>(
        &self,
        py: Python<'py>,
        marginals: Vec<Vec<f64>>,
        targets: Vec<usize>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner
                .count_distribution(&marginals, &targets)
                .raise()?,
        ))
    }
}

/// One term of a `QuotientDrivenWalk`: `("laplacian", None)`,
/// `("adjacency", None)` (minus the adjacency matrix), `("cells", cells)`
/// (the projector onto those cells), `("potential", values)` (one value per
/// cell) or `("uniform", None)`.
fn quotient_term(spec: &Bound<'_, PyAny>) -> PyResult<QuotientTerm> {
    let (kind, arg): (String, Bound<'_, PyAny>) = spec
        .extract()
        .map_err(|_| invalid("each term is a pair (kind, argument)"))?;
    match kind.to_ascii_lowercase().as_str() {
        "laplacian" | "adjacency" => {
            if !arg.is_none() {
                return Err(invalid(format!(
                    "a {kind} term takes None: the graph is the quotient's"
                )));
            }
            Ok(QuotientTerm::Graph(generator(&kind)?))
        }
        "cells" => Ok(QuotientTerm::Cells(arg.extract::<Indices>()?.into_vec())),
        "potential" => Ok(QuotientTerm::Potential(arg.extract()?)),
        "uniform" => Ok(QuotientTerm::Uniform),
        _ => Err(invalid(format!(
            "unknown term '{kind}' (expected laplacian, adjacency, cells, potential or uniform)"
        ))),
    }
}

/// A driven walk `H(t) = Σ_j c_j(t)·H_j` reduced to the cells of a
/// `Quotient`: exact for states in the span of the cell states, in as many
/// dimensions as there are cells (adiabatic search on `K_N` or `Q_d` for
/// any `N`). `evolve` works as `DrivenWalk.evolve` on cell amplitudes.
#[pyclass(name = "QuotientDrivenWalk", module = "metatron_qso", frozen)]
pub struct PyQuotientDrivenWalk {
    inner: QuotientDrivenWalk,
}

#[pymethods]
impl PyQuotientDrivenWalk {
    #[new]
    fn new(quotient: &PyQuotient, terms: Vec<Bound<'_, PyAny>>) -> PyResult<Self> {
        let terms = terms
            .iter()
            .map(quotient_term)
            .collect::<PyResult<Vec<_>>>()?;
        QuotientDrivenWalk::new(&quotient.inner, terms)
            .raise()
            .map(|inner| Self { inner })
    }

    #[getter]
    fn quotient(&self) -> PyQuotient {
        PyQuotient {
            inner: self.inner.quotient().clone(),
        }
    }

    /// The uniform superposition of all nodes, in the cell basis.
    fn uniform_state<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.uniform_state())
    }

    /// Evolve the cell amplitudes `c0` from `t0` to `t1` (as
    /// `DrivenWalk.evolve`).
    #[pyo3(signature = (
        c0, t0, t1, coefficients, tol = 1e-8, initial_step = None, fixed_step = None,
        max_step = None, max_steps = 1_000_000
    ))]
    #[allow(clippy::too_many_arguments)]
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        c0: ComplexArg<'_>,
        t0: f64,
        t1: f64,
        coefficients: &Bound<'py, PyAny>,
        tol: f64,
        initial_step: Option<f64>,
        fixed_step: Option<f64>,
        max_step: Option<f64>,
        max_steps: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let options = MagnusOptions {
            tol,
            initial_step,
            fixed_step,
            max_step,
            max_steps,
        };
        let c0 = complex_vec(&c0);
        driven_result(py, coefficients, |c| {
            self.inner.evolve(&c0, t0, t1, c, &options)
        })
    }

    /// The probability of every cell.
    fn cell_probabilities<'py>(
        &self,
        py: Python<'py>,
        state: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner
                .cell_probabilities(&complex_vec(&state))
                .raise()?,
        ))
    }
}

/// Generators of the permutations of the coordinates of the hypercube
/// `Q_d`, as permutations of its `2^d` nodes (the stabiliser of node 0,
/// without a search; `d ≤ 20`).
#[pyfunction(name = "coordinate_permutations")]
fn coordinate_permutations_py(d: usize) -> PyResult<Vec<Vec<usize>>> {
    coordinate_permutations(d).raise()
}

/// The walk on the hypercube `Q_d` (up to d = 230) with site dephasing at
/// `site_rate` and dephasing of every coordinate at `coordinate_rate`, on
/// the `C(d + 3, 3)` orbitals of the coordinate permutations, without
/// building the graph. Coefficients are those of ρ in the orthonormal
/// basis of the orbitals, so `Σ|x|² = Tr ρ²`; the probability of distance
/// k carries a rounding error of about `1e-16·√C(d, k)`.
///
/// For transport to a trap (up to d = 61), `site_energies`,
/// `node_dephasing` (added to `site_rate`) and `losses` (a number or
/// `d + 1` values) are given by Hamming weight, and `traps` as
/// `{weight: κ}` or `(weight, κ)` pairs: every node of that weight is a
/// trap (weight `d` is the antipode of `0…0`, where the walker starts).
#[pyclass(name = "HypercubeOpenWalk", module = "metatron_qso", frozen)]
pub struct PyHypercubeOpenWalk {
    inner: HypercubeOpenWalk,
}

#[pymethods]
impl PyHypercubeOpenWalk {
    #[new]
    #[pyo3(signature = (
        d, gamma = 1.0, site_rate = 0.0, coordinate_rate = 0.0, site_energies = None,
        node_dephasing = None, traps = None, losses = None
    ))]
    #[allow(clippy::too_many_arguments)]
    fn new(
        py: Python<'_>,
        d: usize,
        gamma: f64,
        site_rate: f64,
        coordinate_rate: f64,
        site_energies: Option<RealArg<'_>>,
        node_dephasing: Option<RealArg<'_>>,
        traps: Option<Bound<'_, PyAny>>,
        losses: Option<Bound<'_, PyAny>>,
    ) -> PyResult<Self> {
        let energies = site_energies.as_ref().map(real_vec);
        let node_rates = node_dephasing.as_ref().map(real_vec);
        let traps = traps.as_ref().map(traps_arg).transpose()?;
        let losses = losses
            .as_ref()
            .map(|l| rates_arg("losses", l, d.saturating_add(1)))
            .transpose()?;
        py.detach(|| -> metatron_qso::Result<HypercubeOpenWalk> {
            let mut w = HypercubeOpenWalk::new(d, gamma, site_rate, coordinate_rate)?;
            if let Some(e) = &energies {
                w = w.with_site_energies(e)?;
            }
            if let Some(r) = &node_rates {
                w = w.with_node_dephasing(r)?;
            }
            if let Some(t) = &traps {
                w = w.with_traps(t)?;
            }
            if let Some(l) = &losses {
                w = w.with_losses(l)?;
            }
            Ok(w)
        })
        .raise()
        .map(|inner| Self { inner })
    }

    /// Efficiency `η`, mean arrival time `τ`, losses and dark weight of a
    /// walker started at `0…0`, by linear solves on the orbitals; needs a
    /// trap. Coherent transport on a large cube is ill-conditioned: `τ`
    /// then loses digits that `error` (an estimate for `η`) does not show.
    #[pyo3(signature = (*, dark_tolerance = 1e-10, tolerance = 1e-13, max_iterations = 1000))]
    fn transport<'py>(
        &self,
        py: Python<'py>,
        dark_tolerance: f64,
        tolerance: f64,
        max_iterations: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let o = transport_options(dark_tolerance, tolerance, max_iterations);
        let w = &self.inner;
        transport_dict(py, py.detach(|| w.transport(&o)).raise()?)
    }

    /// `transport` with each of `rates` (`≥ 0`) added to every node's
    /// dephasing: arrays over the rates.
    #[pyo3(signature = (rates, *, dark_tolerance = 1e-10, tolerance = 1e-13, max_iterations = 1000))]
    fn dephasing_scan<'py>(
        &self,
        py: Python<'py>,
        rates: RealArg<'_>,
        dark_tolerance: f64,
        tolerance: f64,
        max_iterations: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let rates = real_vec(&rates);
        let o = transport_options(dark_tolerance, tolerance, max_iterations);
        let w = &self.inner;
        let results = py.detach(|| w.dephasing_scan(&rates, &o)).raise()?;
        scan_dict(py, rates, results, w.traps().len())
    }

    /// The rate in `[low, high]` which, added to every node's dephasing,
    /// gives the highest efficiency, with the result there.
    #[pyo3(signature = (
        low = 1e-3, high = 1e3, *, dark_tolerance = 1e-10, tolerance = 1e-13,
        max_iterations = 1000
    ))]
    fn optimal_dephasing<'py>(
        &self,
        py: Python<'py>,
        low: f64,
        high: f64,
        dark_tolerance: f64,
        tolerance: f64,
        max_iterations: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let o = transport_options(dark_tolerance, tolerance, max_iterations);
        let w = &self.inner;
        let best = py.detach(|| w.optimal_dephasing(low, high, &o)).raise()?;
        optimum_dict(py, best)
    }

    /// Populations per Hamming weight `0..=d`, sink populations (per trap
    /// weight) and the lost population at each of `times`
    /// (non-decreasing) from `0…0`.
    fn transport_trace<'py>(
        &self,
        py: Python<'py>,
        times: RealArg<'_>,
    ) -> PyResult<Bound<'py, PyDict>> {
        let times = real_vec(&times);
        let w = &self.inner;
        let states = py.detach(|| w.transport_trace(&times)).raise()?;
        trace_dict(py, states, w.dimension() + 1, w.traps().len())
    }

    /// The traps `(weight, κ)` in the order given.
    #[getter]
    fn traps(&self) -> Vec<(usize, f64)> {
        self.inner.traps().to_vec()
    }

    #[getter]
    fn dimension(&self) -> usize {
        self.inner.dimension()
    }

    #[getter]
    fn num_orbitals(&self) -> usize {
        self.inner.num_orbitals()
    }

    /// Index of the orbital with `n01`, `n10` and `n11` coordinates of bits
    /// 01, 10 and 11.
    fn orbital(&self, n01: usize, n10: usize, n11: usize) -> PyResult<usize> {
        self.inner.orbital(n01, n10, n11).raise()
    }

    /// The walker at node 0…0.
    fn localized<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.localized())
    }

    /// The uniform superposition of all nodes.
    fn uniform<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.uniform())
    }

    /// The coefficients after time `t ≥ 0` from `x0`.
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        x0: ComplexArg<'_>,
        t: f64,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (x0, w) = (complex_vec(&x0), &self.inner);
        Ok(complex_array(py, py.detach(|| w.evolve(&x0, t)).raise()?))
    }

    /// The entry ρ_uv of any pair of the orbital `(n01, n10, n11)`.
    fn entry(&self, x: ComplexArg<'_>, n01: usize, n10: usize, n11: usize) -> PyResult<C64> {
        self.inner.entry(&complex_vec(&x), n01, n10, n11).raise()
    }

    /// The probability of every distance from 0…0.
    fn distance_distribution<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner.distance_distribution(&complex_vec(&x)).raise()?,
        ))
    }
}

pub(crate) fn register(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_class::<PyOrbitals>()?;
    m.add_class::<PySymmetricOpenWalk>()?;
    m.add_class::<PySymmetricCoinedWalk>()?;
    m.add_class::<PyProductOpenWalk>()?;
    m.add_class::<PyHypercubeOpenWalk>()?;
    m.add_class::<PyQuotientDrivenWalk>()?;
    m.add_function(wrap_pyfunction!(coordinate_permutations_py, m)?)?;
    Ok(())
}
