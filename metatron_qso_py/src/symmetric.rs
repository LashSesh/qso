/// The orbits of the permutation group generated by `generators`
/// (permutations `u ↦ g[u]` of `0..n`) on ordered pairs of points: the
/// entries an invariant operator has in common. At most 8192 points.
#[pyclass(name = "Orbitals", module = "metatron_qso", frozen)]
pub struct PyOrbitals {
    inner: Arc<Orbitals>,
}

#[pymethods]
impl PyOrbitals {
    #[new]
    #[pyo3(signature = (n, generators = Vec::new()))]
    fn new(py: Python<'_>, n: usize, generators: Vec<Vec<usize>>) -> PyResult<Self> {
        py.detach(|| Orbitals::new(n, &generators))
            .raise()
            .map(|o| Self { inner: Arc::new(o) })
    }

    #[getter]
    fn num_points(&self) -> usize {
        self.inner.num_points()
    }

    fn __len__(&self) -> usize {
        self.inner.len()
    }

    /// The orbital of the pair `(u, v)`.
    fn of(&self, u: usize, v: usize) -> PyResult<usize> {
        let n = self.inner.num_points();
        if u >= n || v >= n {
            return Err(invalid(format!(
                "pair ({u}, {v}) out of range for {n} points"
            )));
        }
        Ok(self.inner.of(u, v))
    }

    /// The first pair of orbital `o`.
    fn representative(&self, o: usize) -> PyResult<(usize, usize)> {
        self.check(o)?;
        Ok(self.inner.representative(o))
    }

    /// Number of pairs in orbital `o`.
    fn size(&self, o: usize) -> PyResult<usize> {
        self.check(o)?;
        Ok(self.inner.size(o))
    }

    /// The coefficients of an `n × n` operator constant on every orbital
    /// (to `tol` of its largest entry).
    #[pyo3(signature = (m, tol = 1e-10))]
    fn coefficients<'py>(
        &self,
        py: Python<'py>,
        m: ComplexMatrixArg<'_>,
        tol: f64,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (dim, data) = square_complex("m", &m)?;
        let m = CMatrix::from_row_slice(dim, dim, &data);
        Ok(complex_array(py, self.inner.coefficients(&m, tol).raise()?))
    }

    /// The `n × n` operator with coefficients `x`.
    fn operator<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray2<C64>>> {
        Ok(cmatrix(py, &self.inner.operator(&complex_vec(&x)).raise()?))
    }

    fn __repr__(&self) -> String {
        format!(
            "Orbitals(points={}, orbitals={})",
            self.inner.num_points(),
            self.inner.len()
        )
    }
}

impl PyOrbitals {
    fn check(&self, o: usize) -> PyResult<()> {
        if o >= self.inner.len() {
            return Err(invalid(format!(
                "orbital {o} out of range for {} orbitals",
                self.inner.len()
            )));
        }
        Ok(())
    }
}

/// `(rate, block)` pairs: dephasing at `rate` between the blocks of the
/// partition `block` (node → block label).
fn dephasing(terms: Vec<(f64, Vec<usize>)>) -> Vec<Dephasing> {
    terms
        .into_iter()
        .map(|(rate, block)| Dephasing { rate, block })
        .collect()
}

/// A continuous-time walk `H = γL` or `−γA` with dephasing
/// `dρ/dt = −i[H, ρ] + Σ_m κ_m (Σ_j P_{m,j} ρ P_{m,j} − ρ)`, reduced to the
/// orbitals of the group generated by `symmetries`.
///
/// `dephasing` is a list of `(rate, block)` pairs, `block[u]` the block of
/// node `u` in that term's partition: `(κ, list(range(n)))` is site
/// dephasing, `(κ, [(u >> k) & 1 for u in range(n)])` dephasing of
/// coordinate `k` of a hypercube. The symmetries must be automorphisms of
/// the graph under which the total decay rate of every entry is invariant;
/// `graph.stabilizer_generators` and `coordinate_permutations` give some
/// (prefer small generating sets: the work grows with their number).
#[pyclass(name = "SymmetricOpenWalk", module = "metatron_qso", frozen)]
pub struct PySymmetricOpenWalk {
    inner: SymmetricOpenWalk,
}

#[pymethods]
impl PySymmetricOpenWalk {
    #[new]
    #[pyo3(signature = (
        graph, generator = "laplacian", gamma = 1.0, dephasing = Vec::new(),
        symmetries = Vec::new()
    ))]
    fn new(
        py: Python<'_>,
        graph: &PyGraph,
        generator: &str,
        gamma: f64,
        dephasing: Vec<(f64, Vec<usize>)>,
        symmetries: Vec<Vec<usize>>,
    ) -> PyResult<Self> {
        let (gen_, terms, g) = (
            self::generator(generator)?,
            self::dephasing(dephasing),
            &graph.inner,
        );
        py.detach(|| SymmetricOpenWalk::new(g, gen_, gamma, &terms, &symmetries))
            .raise()
            .map(|inner| Self { inner })
    }

    #[getter]
    fn num_orbitals(&self) -> usize {
        self.inner.num_orbitals()
    }

    /// The orbitals the state lives on.
    #[getter]
    fn orbitals(&self) -> PyOrbitals {
        PyOrbitals {
            inner: Arc::clone(self.inner.orbitals()),
        }
    }

    /// The coefficients of the walker at `node` (fixed by every symmetry).
    fn localized<'py>(&self, py: Python<'py>, node: usize) -> PyResult<Bound<'py, PyArray1<C64>>> {
        Ok(complex_array(py, self.inner.localized(node).raise()?))
    }

    /// The coefficients of the uniform superposition of all nodes.
    fn uniform<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.uniform())
    }

    /// The coefficients after time `t ≥ 0` from `x0`.
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        x0: ComplexArg<'_>,
        t: f64,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (x0, w) = (complex_vec(&x0), &self.inner);
        Ok(complex_array(py, py.detach(|| w.evolve(&x0, t)).raise()?))
    }

    /// The population of every node.
    fn populations<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner.populations(&complex_vec(&x)).raise()?,
        ))
    }
}

/// A `DecoherentCoinedWalk` reduced to the orbitals of the group generated
/// by `symmetries` (automorphisms of its graph, as node permutations), on
/// pairs of arcs. The coin must be invariant (the Grover coin is); coin
/// dephasing only under symmetries that keep the order of the arcs at
/// every node.
#[pyclass(name = "SymmetricCoinedWalk", module = "metatron_qso", frozen)]
pub struct PySymmetricCoinedWalk {
    inner: SymmetricCoinedWalk,
}

#[pymethods]
impl PySymmetricCoinedWalk {
    #[new]
    #[pyo3(signature = (walk, symmetries = Vec::new()))]
    fn new(
        py: Python<'_>,
        walk: &PyDecoherentCoinedWalk,
        symmetries: Vec<Vec<usize>>,
    ) -> PyResult<Self> {
        let w = &walk.inner;
        py.detach(|| SymmetricCoinedWalk::new(w, &symmetries))
            .raise()
            .map(|inner| Self { inner })
    }

    #[getter]
    fn num_orbitals(&self) -> usize {
        self.inner.num_orbitals()
    }

    #[getter]
    fn orbitals(&self) -> PyOrbitals {
        PyOrbitals {
            inner: Arc::clone(self.inner.orbitals()),
        }
    }

    /// The walker at `node` with the uniform coin state.
    fn localized<'py>(&self, py: Python<'py>, node: usize) -> PyResult<Bound<'py, PyArray1<C64>>> {
        Ok(complex_array(py, self.inner.localized(node).raise()?))
    }

    /// The coefficients after `steps` steps from `x0`.
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        x0: ComplexArg<'_>,
        steps: usize,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (x0, w) = (complex_vec(&x0), &self.inner);
        Ok(complex_array(
            py,
            py.detach(|| w.evolve(&x0, steps)).raise()?,
        ))
    }

    /// Probability of each node.
    fn node_probabilities<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner.node_probabilities(&complex_vec(&x)).raise()?,
        ))
    }
}

/// A walk on the Cartesian product of graphs whose factors dephase
/// independently, from a product state: `factors` is a list of
/// `(DephasingWalk, copies)`; the hypercube `Q_d` with dephasing per
/// coordinate is `[(DephasingWalk(complete(2), …), d)]`.
#[pyclass(name = "ProductOpenWalk", module = "metatron_qso", frozen)]
pub struct PyProductOpenWalk {
    inner: ProductOpenWalk,
}

#[pymethods]
impl PyProductOpenWalk {
    #[new]
    fn new(factors: Vec<(PyRef<'_, PyDephasingWalk>, usize)>) -> PyResult<Self> {
        let factors = factors.iter().map(|(w, k)| (w.inner.clone(), *k)).collect();
        ProductOpenWalk::new(factors)
            .raise()
            .map(|inner| Self { inner })
    }

    /// The node populations of each factor at time `t`, every copy of
    /// factor `k` started at `starts[k]`.
    fn marginals(&self, py: Python<'_>, starts: Vec<usize>, t: f64) -> PyResult<Vec<Vec<f64>>> {
        let w = &self.inner;
        py.detach(|| w.marginals(&starts, t)).raise()
    }

    /// The distribution of the number of copies at their target node
    /// (`targets[k]` for factor `k`), from `marginals`.
    fn count_distribution<'py>(
        &self,
        py: Python<'py>,
        marginals: Vec<Vec<f64>>,
        targets: Vec<usize>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner
                .count_distribution(&marginals, &targets)
                .raise()?,
        ))
    }
}

/// One term of a `QuotientDrivenWalk`: `("laplacian", None)`,
/// `("adjacency", None)` (minus the adjacency matrix), `("cells", cells)`
/// (the projector onto those cells), `("potential", values)` (one value per
/// cell) or `("uniform", None)`.
fn quotient_term(spec: &Bound<'_, PyAny>) -> PyResult<QuotientTerm> {
    let (kind, arg): (String, Bound<'_, PyAny>) = spec
        .extract()
        .map_err(|_| invalid("each term is a pair (kind, argument)"))?;
    match kind.to_ascii_lowercase().as_str() {
        "laplacian" | "adjacency" => {
            if !arg.is_none() {
                return Err(invalid(format!(
                    "a {kind} term takes None: the graph is the quotient's"
                )));
            }
            Ok(QuotientTerm::Graph(generator(&kind)?))
        }
        "cells" => Ok(QuotientTerm::Cells(arg.extract::<Indices>()?.into_vec())),
        "potential" => Ok(QuotientTerm::Potential(arg.extract()?)),
        "uniform" => Ok(QuotientTerm::Uniform),
        _ => Err(invalid(format!(
            "unknown term '{kind}' (expected laplacian, adjacency, cells, potential or uniform)"
        ))),
    }
}

/// A driven walk `H(t) = Σ_j c_j(t)·H_j` reduced to the cells of a
/// `Quotient`: exact for states in the span of the cell states, in as many
/// dimensions as there are cells (adiabatic search on `K_N` or `Q_d` for
/// any `N`). `evolve` works as `DrivenWalk.evolve` on cell amplitudes.
#[pyclass(name = "QuotientDrivenWalk", module = "metatron_qso", frozen)]
pub struct PyQuotientDrivenWalk {
    inner: QuotientDrivenWalk,
}

#[pymethods]
impl PyQuotientDrivenWalk {
    #[new]
    fn new(quotient: &PyQuotient, terms: Vec<Bound<'_, PyAny>>) -> PyResult<Self> {
        let terms = terms
            .iter()
            .map(quotient_term)
            .collect::<PyResult<Vec<_>>>()?;
        QuotientDrivenWalk::new(&quotient.inner, terms)
            .raise()
            .map(|inner| Self { inner })
    }

    #[getter]
    fn quotient(&self) -> PyQuotient {
        PyQuotient {
            inner: self.inner.quotient().clone(),
        }
    }

    /// The uniform superposition of all nodes, in the cell basis.
    fn uniform_state<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.uniform_state())
    }

    /// Evolve the cell amplitudes `c0` from `t0` to `t1` (as
    /// `DrivenWalk.evolve`).
    #[pyo3(signature = (
        c0, t0, t1, coefficients, tol = 1e-8, initial_step = None, fixed_step = None,
        max_step = None, max_steps = 1_000_000
    ))]
    #[allow(clippy::too_many_arguments)]
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        c0: ComplexArg<'_>,
        t0: f64,
        t1: f64,
        coefficients: &Bound<'py, PyAny>,
        tol: f64,
        initial_step: Option<f64>,
        fixed_step: Option<f64>,
        max_step: Option<f64>,
        max_steps: usize,
    ) -> PyResult<Bound<'py, PyDict>> {
        let options = MagnusOptions {
            tol,
            initial_step,
            fixed_step,
            max_step,
            max_steps,
        };
        let c0 = complex_vec(&c0);
        driven_result(py, coefficients, |c| {
            self.inner.evolve(&c0, t0, t1, c, &options)
        })
    }

    /// The probability of every cell.
    fn cell_probabilities<'py>(
        &self,
        py: Python<'py>,
        state: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner
                .cell_probabilities(&complex_vec(&state))
                .raise()?,
        ))
    }
}

/// Generators of the permutations of the coordinates of the hypercube
/// `Q_d`, as permutations of its `2^d` nodes (the stabiliser of node 0,
/// without a search).
#[pyfunction(name = "coordinate_permutations")]
fn coordinate_permutations_py(d: usize) -> PyResult<Vec<Vec<usize>>> {
    coordinate_permutations(d).raise()
}

/// The walk on the hypercube `Q_d` (up to d = 230) with site dephasing at
/// `site_rate` and dephasing of every coordinate at `coordinate_rate`, on
/// the `C(d + 3, 3)` orbitals of the coordinate permutations, without
/// building the graph. Coefficients are those of ρ in the orthonormal
/// basis of the orbitals, so `Σ|x|² = Tr ρ²`; the probability of distance
/// k carries a rounding error of about `1e-16·√C(d, k)`.
#[pyclass(name = "HypercubeOpenWalk", module = "metatron_qso", frozen)]
pub struct PyHypercubeOpenWalk {
    inner: HypercubeOpenWalk,
}

#[pymethods]
impl PyHypercubeOpenWalk {
    #[new]
    #[pyo3(signature = (d, gamma = 1.0, site_rate = 0.0, coordinate_rate = 0.0))]
    fn new(
        py: Python<'_>,
        d: usize,
        gamma: f64,
        site_rate: f64,
        coordinate_rate: f64,
    ) -> PyResult<Self> {
        py.detach(|| HypercubeOpenWalk::new(d, gamma, site_rate, coordinate_rate))
            .raise()
            .map(|inner| Self { inner })
    }

    #[getter]
    fn dimension(&self) -> usize {
        self.inner.dimension()
    }

    #[getter]
    fn num_orbitals(&self) -> usize {
        self.inner.num_orbitals()
    }

    /// Index of the orbital with `n01`, `n10` and `n11` coordinates of bits
    /// 01, 10 and 11.
    fn orbital(&self, n01: usize, n10: usize, n11: usize) -> PyResult<usize> {
        self.inner.orbital(n01, n10, n11).raise()
    }

    /// The walker at node 0…0.
    fn localized<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.localized())
    }

    /// The uniform superposition of all nodes.
    fn uniform<'py>(&self, py: Python<'py>) -> Bound<'py, PyArray1<C64>> {
        complex_array(py, self.inner.uniform())
    }

    /// The coefficients after time `t ≥ 0` from `x0`.
    fn evolve<'py>(
        &self,
        py: Python<'py>,
        x0: ComplexArg<'_>,
        t: f64,
    ) -> PyResult<Bound<'py, PyArray1<C64>>> {
        let (x0, w) = (complex_vec(&x0), &self.inner);
        Ok(complex_array(py, py.detach(|| w.evolve(&x0, t)).raise()?))
    }

    /// The entry ρ_uv of any pair of the orbital `(n01, n10, n11)`.
    fn entry(&self, x: ComplexArg<'_>, n01: usize, n10: usize, n11: usize) -> PyResult<C64> {
        self.inner.entry(&complex_vec(&x), n01, n10, n11).raise()
    }

    /// The probability of every distance from 0…0.
    fn distance_distribution<'py>(
        &self,
        py: Python<'py>,
        x: ComplexArg<'_>,
    ) -> PyResult<Bound<'py, PyArray1<f64>>> {
        Ok(real_array(
            py,
            self.inner.distance_distribution(&complex_vec(&x)).raise()?,
        ))
    }
}

pub(crate) fn register(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_class::<PyOrbitals>()?;
    m.add_class::<PySymmetricOpenWalk>()?;
    m.add_class::<PySymmetricCoinedWalk>()?;
    m.add_class::<PyProductOpenWalk>()?;
    m.add_class::<PyHypercubeOpenWalk>()?;
    m.add_class::<PyQuotientDrivenWalk>()?;
    m.add_function(wrap_pyfunction!(coordinate_permutations_py, m)?)?;
    Ok(())
}
