"""Write metatron-qso-rs/src/chemistry/basis_data.rs from PySCF's copy of
the Basis Set Exchange data.

    python scripts/generate_basis_data.py   # needs pyscf

Each general contraction (several coefficient columns over the same
exponents) becomes one shell per column; zero coefficients are dropped.
Shells keep PySCF's order (by angular momentum, then as listed), so basis
functions come out in PySCF's order.
"""

from pathlib import Path

import pyscf
from pyscf import gto

SYMBOLS = ["H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne",
           "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar"]
BASES = [
    ("STO_3G", "sto-3g", "STO-3G"),
    ("SIX_31G", "6-31g", "6-31G"),
    ("SIX_31G_STAR", "6-31g*", "6-31G*"),
    ("CC_PVDZ", "cc-pvdz", "cc-pVDZ"),
]

HEADER = f"""//! Basis-set data for H to Ar, generated by
//! `scripts/generate_basis_data.py` from PySCF {pyscf.__version__}'s copy of
//! the Basis Set Exchange data: STO-3G (Hehre, Stewart and Pople 1969;
//! Hehre, Ditchfield, Stewart and Pople 1970), 6-31G (Ditchfield, Hehre and
//! Pople 1971; Hehre, Ditchfield and Pople 1972; Francl et al. 1982),
//! 6-31G* (Hariharan and Pople 1973; Francl et al. 1982) and cc-pVDZ
//! (Dunning 1989; Woon and Dunning 1993). Coefficients refer to normalised
//! primitives; a general contraction is one shell per column.

/// A contracted shell: angular momentum and `(exponent, coefficient)` pairs.
pub(crate) type ShellData = (u8, &'static [(f64, f64)]);

/// Elements with basis data (atomic numbers 1 to this).
pub(crate) const ELEMENTS: usize = {len(SYMBOLS)};
"""


def shells(name: str, symbol: str) -> list[tuple[int, list[tuple[float, float]]]]:
    out = []
    for entry in gto.basis.load(name, symbol):
        l = entry[0]
        rows = entry[1:]
        if isinstance(rows[0], (int, float)) and not isinstance(rows[0], list):
            rows = rows[1:]  # kappa
        for col in range(1, len(rows[0])):
            prims = [(float(r[0]), float(r[col])) for r in rows if float(r[col]) != 0.0]
            out.append((l, prims))
    return out


def main() -> None:
    text = HEADER
    for const, name, title in BASES:
        text += f"\n/// {title}, by atomic number − 1.\npub(crate) const {const}: [&[ShellData]; ELEMENTS] = [\n"
        for symbol in SYMBOLS:
            text += f"    // {symbol}\n    &[\n"
            for l, prims in shells(name, symbol):
                body = ", ".join(f"({e!r}, {c!r})" for e, c in prims)
                text += f"        ({l}, &[{body}]),\n"
            text += "    ],\n"
        text += "];\n"
    path = Path(__file__).resolve().parent.parent / "metatron-qso-rs/src/chemistry/basis_data.rs"
    path.write_text(text)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
