"""Reference data of the Pauli-propagation validation tests (1.64).

Writes two files into metatron-qso-rs/tests/data/:

* heavy_hex_7.json: Qiskit's CouplingMap.from_heavy_hex(7) (115 qubits,
  132 edges) as three colour classes of 44 edges each, from rustworkx's
  graph_bipartite_edge_color (colour order 0, 1, 2; each class sorted).
  One kicked-Ising step is RX(theta_h) on every qubit, then RZZ(-pi/2) on
  the edges of colour 0, 1 and 2 (Kim et al., Nature 618, 500 (2023)).
* stim_before_1000.json: a seeded Clifford circuit of 10^4 gates on 1000
  qubits, generated by splitmix64 (so that the Rust test regenerates it
  without the file listing the gates), and Stim's PauliString.before of
  Z_q for 20 qubits q: the Heisenberg operator C^dag Z_q C with its sign.

Run with the pinned packages of requirements.txt plus stim 1.16:

    python benchmarks/cross_framework/propagation_data.py
"""

import json
import pathlib

import rustworkx as rx
import stim
from qiskit.transpiler import CouplingMap

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "metatron-qso-rs" / "tests" / "data"

MASK = (1 << 64) - 1

# Gate set of the Clifford circuit: Stim name, number of qubits. The Rust
# test maps them to h, s, sdg, sx, sxdg, x, y, z, cx, cy, cz, swap.
GATES = [
    ("H", 1), ("S", 1), ("S_DAG", 1), ("SQRT_X", 1), ("SQRT_X_DAG", 1),
    ("X", 1), ("Y", 1), ("Z", 1), ("CX", 2), ("CY", 2), ("CZ", 2), ("SWAP", 2),
]


class SplitMix64:
    """splitmix64 (Steele, Lea and Flood 2014), the generator the Rust test
    reimplements."""

    def __init__(self, seed):
        self.state = seed & MASK

    def next(self):
        self.state = (self.state + 0x9E3779B97F4A7C15) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        return z ^ (z >> 31)

    def below(self, n):
        return self.next() % n


def clifford_ops(n, gates, seed):
    """[(stim name, qubits)]: each gate a uniform kind, a uniform first
    qubit and, for two-qubit gates, a uniform other qubit."""
    rng = SplitMix64(seed)
    ops = []
    for _ in range(gates):
        name, arity = GATES[rng.below(len(GATES))]
        a = rng.below(n)
        if arity == 1:
            ops.append((name, [a]))
        else:
            b = (a + 1 + rng.below(n - 1)) % n
            ops.append((name, [a, b]))
    return ops


def heavy_hex():
    cm = CouplingMap.from_heavy_hex(7)
    g = cm.graph.to_undirected(multigraph=False)
    colour = rx.graph_bipartite_edge_color(g)
    classes = [[], [], []]
    for idx in g.edge_indices():
        a, b = g.get_edge_endpoints_by_index(idx)
        classes[colour[idx]].append([min(a, b), max(a, b)])
    classes = [sorted(c) for c in classes]
    n = cm.size()
    for c in classes:
        qs = [q for e in c for q in e]
        assert len(qs) == len(set(qs))
    assert n == 115 and [len(c) for c in classes] == [44, 44, 44]
    return {
        "source": "qiskit CouplingMap.from_heavy_hex(7), rustworkx "
                  "graph_bipartite_edge_color; generated by "
                  "benchmarks/cross_framework/propagation_data.py",
        "n_qubits": n,
        "central_qubit": n // 2,
        "colours": classes,
    }


def stim_before(n=1000, gates=10_000, seed=1640, strings=20):
    ops = clifford_ops(n, gates, seed)
    circuit = stim.Circuit()
    for name, qs in ops:
        circuit.append(name, qs)
    qubits = [(37 * k + 11) % n for k in range(strings)]
    out = []
    for q in qubits:
        p = stim.PauliString(n)
        p[q] = "Z"
        before = p.before(circuit)
        text = str(before)  # "+_XZY..." with '_' for the identity
        out.append({"qubit": q, "before": text,
                    "weight": sum(ch != "_" for ch in text[1:])})
    return {
        "source": f"stim {stim.__version__} PauliString.before; generated by "
                  "benchmarks/cross_framework/propagation_data.py",
        "n_qubits": n,
        "gates": gates,
        "seed": seed,
        "generator": "splitmix64: per gate kind = below(12) into "
                     + ", ".join(g for g, _ in GATES)
                     + "; a = below(n); two-qubit: b = (a + 1 + below(n - 1)) % n; "
                       "below(m) = next() % m",
        "first_gates": [[name] + qs for name, qs in ops[:8]],
        "strings": out,
    }


def main():
    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "heavy_hex_7.json").write_text(json.dumps(heavy_hex()) + "\n")
    (DATA / "stim_before_1000.json").write_text(json.dumps(stim_before(), indent=1) + "\n")


if __name__ == "__main__":
    main()
